model = joblib.load("flipkart_low_csat_model.pkl")
input_options = joblib.load("input_options.pkl")

st.markdown("""
<div class="hero">
    <p>FLIPKART SUPPORT OPERATIONS</p>
    <h1>CSAT Risk Console</h1>
    <span>Predict the probability that a support ticket will receive a low CSAT score.</span>
</div>
""", unsafe_allow_html=True)

st.info(
    "This model predicts low-CSAT risk, not the exact CSAT score. "
    "High risk means the ticket should be prioritised."
)

with st.form("csat_prediction_form"):

    st.markdown(
        '<p class="section-title">1. Ticket Context</p>',
        unsafe_allow_html=True
    )

    col1, col2, col3 = st.columns(3)

    with col1:
        channel_name = st.selectbox(
            "Channel Name",
            input_options["channel_name"]
        )

    with col2:
        category = st.selectbox(
            "Issue Category",
            input_options["category"]
        )

    with col3:
        sub_category = st.selectbox(
            "Sub-category",
            input_options["Sub-category"]
        )

    customer_remarks = st.text_input(
        "Customer Remarks",
        value="No Remarks",
        help="Use the customer's issue summary or select No Remarks."
    )

    st.markdown(
        '<p class="section-title">2. Support Team Details</p>',
        unsafe_allow_html=True
    )

    col4, col5, col6 = st.columns(3)

    with col4:
        agent_name = st.selectbox(
            "Agent Name",
            input_options["Agent_name"]
        )

        tenure_bucket = st.selectbox(
            "Tenure Bucket",
            input_options["Tenure Bucket"]
        )

    with col5:
        supervisor = st.selectbox(
            "Supervisor",
            input_options["Supervisor"]
        )

        agent_shift = st.selectbox(
            "Agent Shift",
            input_options["Agent Shift"]
        )

    with col6:
        manager = st.selectbox(
            "Manager",
            input_options["Manager"]
        )

    st.markdown(
        '<p class="section-title">3. Ticket Timeline</p>',
        unsafe_allow_html=True
    )

    col7, col8, col9 = st.columns(3)

    with col7:
        issue_date = st.date_input("Issue Reported Date")
        issue_time = st.time_input("Issue Reported Time")

    with col8:
        response_date = st.date_input("Issue Responded Date")
        response_time = st.time_input("Issue Responded Time")

    with col9:
        survey_date = st.date_input("Survey Response Date")

    submitted = st.form_submit_button("Predict Low CSAT Risk")

if submitted:

    issue_datetime = pd.to_datetime(
        str(issue_date) + " " + str(issue_time)
    )

    response_datetime = pd.to_datetime(
        str(response_date) + " " + str(response_time)
    )

    survey_datetime = pd.to_datetime(str(survey_date))

    response_time_mins = (
        response_datetime - issue_datetime
    ).total_seconds() / 60

    if response_time_mins < 0:
        st.error(
            "Response date/time cannot be earlier than issue date/time."
        )

    else:
        input_data = pd.DataFrame({
            "channel_name": [channel_name],
            "category": [category],
            "Sub-category": [sub_category],
            "Customer Remarks": [customer_remarks],
            "Agent_name": [agent_name],
            "Supervisor": [supervisor],
            "Manager": [manager],
            "Tenure Bucket": [tenure_bucket],
            "Agent Shift": [agent_shift],
            "response_time_mins": [response_time_mins],
            "issue_hour": [issue_datetime.hour],
            "issue_day": [issue_datetime.day],
            "issue_month": [issue_datetime.month],
            "issue_dayofweek": [issue_datetime.dayofweek],
            "response_hour": [response_datetime.hour],
            "survey_day": [survey_datetime.day],
            "survey_month": [survey_datetime.month]
        })

        prediction = model.predict(input_data)[0]
        low_csat_risk = model.predict_proba(input_data)[0][1]

        st.markdown("---")
        st.subheader("Prediction Result")

        metric1, metric2, metric3 = st.columns(3)

        metric1.metric(
            "Low CSAT Risk",
            f"{low_csat_risk * 100:.1f}%"
        )

        metric2.metric(
            "Response Time",
            f"{response_time_mins:.0f} minutes"
        )

        if prediction == 1:
            metric3.metric("Ticket Status", "High Risk")

            st.markdown(f"""
            <div class="result-card high-risk">
                <h2>High Risk of Low CSAT</h2>
                <p>This ticket should be prioritised for faster and higher-quality resolution.</p>
            </div>
            """, unsafe_allow_html=True)

            st.markdown("### Recommended Actions")
            st.write("- Escalate the ticket to the supervisor.")
            st.write("- Contact the customer quickly with a clear resolution update.")
            st.write("- Review the issue category and agent workload.")

        else:
            metric3.metric("Ticket Status", "Low Risk")

            st.markdown(f"""
            <div class="result-card low-risk">
                <h2>Low Risk of Low CSAT</h2>
                <p>The ticket is predicted to have a lower chance of poor customer satisfaction.</p>
            </div>
            """, unsafe_allow_html=True)

            st.markdown("### Recommended Actions")
            st.write("- Continue with the standard support process.")
            st.write("- Maintain clear communication with the customer.")
            st.write("- Monitor the ticket if the response time increases.")