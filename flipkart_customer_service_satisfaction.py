print("Shape :",df.shape)

df.head()

df.tail()

df.info()

df.describe()

"""### Step 4: Check Missing Values"""

df.isnull().sum()

# 1. Highly missing / less useful columns drop
df.drop(columns=[
    'connected_handling_time',
    'order_date_time',
    'Customer_City',
    'Product_category',
    'Item_price',
    'Order_id'
], inplace=True)

# 2. Customer Remarks me missing fill karo
df['Customer Remarks'] = df['Customer Remarks'].fillna('No Remarks')

# 3. Check after cleaning
print("Missing values after cleaning:\n")
print(df.isnull().sum().sort_values(ascending=False))

"""### Step 5: Check Duplicate Values"""

# 1. Check duplicates
print("Duplicate rows:", df.duplicated().sum())

# Agar duplicates milte hain to remove karo
df.drop_duplicates(inplace=True)

print("Shape after removing duplicates:", df.shape)

# 2. Date columns convert karo
df['Issue_reported at'] = pd.to_datetime(df['Issue_reported at'], dayfirst=True, errors='coerce')
df['issue_responded'] = pd.to_datetime(df['issue_responded'], dayfirst=True, errors='coerce')
df['Survey_response_Date'] = pd.to_datetime(df['Survey_response_Date'], errors='coerce')

# 3. Check datatypes
print("\nUpdated data types:\n")
print(df.dtypes)

"""### Step 5: Feature Engineering

Machine Learning models perform better with meaningful features. Instead of directly using Date columns, we create
Resolution Time,
Order Month,
Order Day,
Weekend,
Order Hour
These new features help the model learn customer behaviour better.
"""

# 1. Response time in minutes
df['response_time_mins'] = (df['issue_responded'] - df['Issue_reported at']).dt.total_seconds() / 60

# 2. Date-based features
df['issue_hour'] = df['Issue_reported at'].dt.hour
df['issue_day'] = df['Issue_reported at'].dt.day
df['issue_month'] = df['Issue_reported at'].dt.month
df['issue_dayofweek'] = df['Issue_reported at'].dt.dayofweek

df['response_hour'] = df['issue_responded'].dt.hour
df['survey_day'] = df['Survey_response_Date'].dt.day
df['survey_month'] = df['Survey_response_Date'].dt.month

# 3. Check negative response times
print("Negative response times:", (df['response_time_mins'] < 0).sum())

# 4. Keep only valid response times
df = df[df['response_time_mins'] >= 0]

# 5. Check result
print(df[['response_time_mins', 'issue_hour', 'issue_day', 'issue_month', 'issue_dayofweek']].head())
print("Shape after feature engineering:", df.shape)

"""### Step 6: Target Analysis"""

# 1. CSAT Score distribution
print("CSAT Score Distribution:\n")
print(df['CSAT Score'].value_counts().sort_index())

# 2. CSAT Score percentage distribution
print("\nCSAT Score Percentage Distribution:\n")
print((df['CSAT Score'].value_counts(normalize=True).sort_index() * 100).round(2))

# 3. Plot CSAT Score distribution
plt.figure(figsize=(8,5))
sns.countplot(x='CSAT Score', data=df)
plt.title("CSAT Score Distribution")
plt.xlabel("CSAT Score")
plt.ylabel("Count")
plt.show()

# 4. Create binary target column
df['low_csat'] = df['CSAT Score'].apply(lambda x: 1 if x <= 3 else 0)

# 5. Check binary target distribution
print("\nLow CSAT Count:\n")
print(df['low_csat'].value_counts())

# 6. Check binary target percentage
print("\nLow CSAT Percentage:\n")
print((df['low_csat'].value_counts(normalize=True) * 100).round(2))

# 7. Plot binary target distribution
plt.figure(figsize=(6,4))
sns.countplot(x='low_csat', data=df)
plt.title("Low CSAT Distribution")
